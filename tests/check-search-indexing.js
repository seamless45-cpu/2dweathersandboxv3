'use strict';
const assert = require('assert');
const fs = require('fs');
const cp = require('child_process');
const root = 'https://seamless45-cpu.github.io/2dweathersandboxv3/';
const html = fs.readFileSync('index.html', 'utf8');
const robots = fs.readFileSync('robots.txt', 'utf8');
assert.match(html, /<meta name="robots" content="index, follow"/);
assert(html.includes(`<link rel="canonical" href="${root}"`));
assert(html.includes(`<meta property="og:url" content="${root}"`));
assert.match(html, /<link rel="sitemap" type="application\/xml" href="sitemap\.xml"/);
assert.match(html, /<meta name="description"\s+content="[^"]{80,}"/);
assert.match(html, /<h1>2D Weather Sandbox<\/h1>/);
assert.match(html, /Explore a real-time 2D weather sandbox/);
const structured = JSON.parse(html.match(/<script type="application\/ld\+json">\s*([\s\S]*?)\s*<\/script>/)[1]);
assert.equal(structured['@type'], 'WebApplication');
assert.equal(structured.url, root);
assert.match(robots, /^User-agent: \*$/m);
assert.match(robots, /^Allow: \/$/m);
assert(robots.includes(`Sitemap: ${root}sitemap.xml`));
const locs = JSON.parse(cp.execFileSync('python3', ['-c', `import json,xml.etree.ElementTree as E; r=E.parse('sitemap.xml').getroot(); print(json.dumps([x.text for x in r.findall('{http://www.sitemaps.org/schemas/sitemap/0.9}url/{http://www.sitemaps.org/schemas/sitemap/0.9}loc')]))`], {encoding:'utf8'}));
assert.deepStrictEqual(locs, [root]);
for (const property of ['og:image','twitter:image']) {
 const m = html.match(new RegExp(`<meta (?:property|name)="${property}" content="([^"]+)"`));
 assert(m && m[1].startsWith(root), property);
 assert(fs.existsSync(m[1].slice(root.length)), property + ' asset missing');
}
const manifest = JSON.parse(fs.readFileSync('manifest.webmanifest', 'utf8'));
const version = fs.readFileSync('sw.js', 'utf8').match(/const VERSION = '([^']+)'/)[1];
for (const icon of manifest.icons) assert(icon.src.endsWith('?v=' + version), 'icon cache buster');
assert(html.includes('favicon.ico?v=' + version));
const ico = fs.readFileSync('favicon.ico');
assert.equal(ico.readUInt16LE(0), 0);
assert.equal(ico.readUInt16LE(2), 1);
assert(ico.readUInt16LE(4) >= 3, 'favicon should include multiple sizes');
const icon = fs.readFileSync('resources/icons/app/icon-512.png');
const mask = fs.readFileSync('resources/icons/app/icon-maskable-512.png');
assert(!icon.equals(mask), 'maskable artwork should retain the wider safe area');
console.log('Canonical URL, search metadata, sitemap and icons verified');

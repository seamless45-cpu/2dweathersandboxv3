'use strict';
const assert=require('assert'),fs=require('fs');
const bright=fs.readFileSync('shaders/fragment/isolateBrightPartsShader.frag','utf8');
const post=fs.readFileSync('shaders/fragment/postProcessingShader.frag','utf8');
assert.match(bright,/texture\(hdrTex, texCoord\)\.rgb/);
assert.match(bright,/outputCol \*= 0\.02/);
assert.doesNotMatch(bright,/lightningBloomGain|brightSample/);
const map=post.slice(post.indexOf('vec3 sourceMappedColor(vec2 uv)'),post.indexOf('\nvoid main()'));
assert.match(map,/bloom = safeSample\(texture\(bloomTex, uv\)\.rgb\) \* 0\.990/);
assert.match(map,/mapRadiance\(scene \+ bloom\)/);
console.log('Upstream 2% HDR bloom and 0.990 composite checks passed');

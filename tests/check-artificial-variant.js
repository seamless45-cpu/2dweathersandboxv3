'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const app = fs.readFileSync('app.js','utf8');
const html = fs.readFileSync('index.html','utf8');
const location = fs.readFileSync('shaders/fragment/lightningLocationShader.frag','utf8');
const table = name => vm.runInNewContext('(' + app.match(new RegExp('const ' + name + ' = (\\{[\\s\\S]*?\\});'))[1] + ')');
const options = table('artificialVariantOptions'), uniforms = table('artificialVariantUniforms');
const expected = {ordinary_cg:0, intra_cloud:1, positive_ic:2, cc_negative:3, cc_positive:4, positive_cg:5, superbolt:6, hyperbolt:12};
assert.deepStrictEqual(JSON.parse(JSON.stringify(uniforms)), expected);
assert.deepStrictEqual(Object.values(options), Object.keys(expected));
for (const removed of ['ground_to_cloud','anvil_crawler','blue_jet','red_sprite','elve']) assert(!(removed in uniforms));
assert.match(app, /hasOwnProperty\.call\(artificialVariantUniforms, guiControls\.artificialLightningVariant\)/);
assert.match(app, /guiControls\.artificialLightningVariant = 'ordinary_cg';/);
assert.match(app, /artificialVariantUniforms\[manualStrike \? manualStrike\.variant : guiControls\.artificialLightningVariant\] \?\? 0/);
assert.match(location, /variant > 11\.5 && variant < 12\.5/);
assert.doesNotMatch(location, /variant > (?:6|7|8|9|10)\.5 && variant </);
assert.doesNotMatch(html, /ground-to-cloud, anvil crawler, blue jet, red sprite or elve/);
console.log('Artificial variant selection and saved-key fallback passed');
